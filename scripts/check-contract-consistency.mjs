import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const metadata = JSON.parse(readFileSync("contracts/phase04-baselines.json", "utf8"));
const sources = metadata.sources;
assert.equal(metadata.status, "PROPOSED_NOT_APPROVED");
assert.equal(metadata.ownerApproval, null, "Owner signoff must not be invented");
const catalog = readFileSync(sources.requirements.file, "utf8");
const ids = [...new Set(catalog.match(/\b(?:FR|NFR)-[0-9]{3}\b/g) || [])];
assert.equal(ids.filter((id) => id.startsWith("FR-")).length, sources.requirements.expectedFR);
assert.equal(ids.filter((id) => id.startsWith("NFR-")).length, sources.requirements.expectedNFR);
const sql = readFileSync(sources.database.file, "utf8");
const tables = sql.match(/\bCREATE TABLE\s+(?:IF NOT EXISTS\s+)?[a-z_]+/gi) || [];
assert.equal(tables.length, sources.database.expectedTables);
const api = JSON.parse(readFileSync(sources.openapi.file, "utf8"));
const paths = Object.values(api.paths);
assert.equal(paths.length, sources.openapi.expectedPaths);
const methods = new Set(["get", "put", "post", "patch", "delete", "options", "head"]);
const ops = paths.reduce((n, item) => n + Object.keys(item).filter((key) => methods.has(key)).length, 0);
assert.equal(ops, sources.openapi.expectedOperations);
const routes = readFileSync(sources.ui.file, "utf8").trim().split(/\r?\n/);
assert.equal(routes.length - 1, sources.ui.expectedRoutes);
assert.match(readFileSync(sources.srs.file, "utf8"), /NOT OWNER-APPROVED/);
assert.match(sql, /DO NOT APPLY TO PRODUCTION/);
console.log(`Candidate contract artifacts consistent: ${ids.length} FR/NFR, ${tables.length} SQL tables, ${paths.length} OpenAPI paths, ${ops} operations, ${routes.length - 1} SSR/UI routes.`);
console.log("Open owner gates remain unresolved; no approvals or final migrations have been inferred.");
